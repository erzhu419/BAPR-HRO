"""Received forecast revisions on the frozen railway trip-chain model.

The Gaussian bandwidth is the declared training-route departure spread, with
a 30-second floor. It is not a fitted forecast-error likelihood. Only the
latest prediction for an event supplies a soft emission; future publications
are never generated by this model. Service notices remain public notices,
not actual cancellation observations.

THEORY/SCOPE: public CANCELED/SKIPPED notices impose a common current-planning
availability mask; they do not condition the physical service law. A later
explicit operating notice, or the same endpoint's first-hand operating
receipt, overrides that mask. NO_DATA withdraws a numerical prediction but is
not a declaration that a skipped stop is served. Future announcements are not
generated, so a frozen masked waiting table is a planning reference rather
than an exact physical value of later receipt-driven execution.
"""

import numpy as np

from experiments.reconstruction_v32.conditional import departure_evidence, UnsupportedHistory
from experiments.reconstruction_v33.history import ConditionalEngine
from experiments.reconstruction_v33.planner import Planner
from src.evolving_trip_belief import _ChainLaw


class MessageHistory(ConditionalEngine):
    def __init__(self, belief, parameters, *, frames=(), source_to_local=None, forecast_sd=None):
        super().__init__(belief, parameters)
        self.frames, self.frame_index = tuple(frames), 0
        self.message_clock = -np.inf
        self.source_to_local = ({c.id: c.id for c in belief.graph.connections}
                                if source_to_local is None else dict(source_to_local))
        self.forecast_sd = ({c.id: max(30., parameters.get(c.route,
            parameters.get('pooled', {'std': 2.}))['std']*60.)
            for c in belief.graph.connections} if forecast_sd is None else dict(forecast_sd))
        self._forecasts, self._endpoint_statuses, self._trip_statuses = {}, {}, {}
        self._service_statuses = {}
        self._forecast_views, self._status_views, self._service_views = {}, {}, {}
        self._trip_cids = {}
        for c in belief.graph.connections:
            self._trip_cids.setdefault(c.trip_id, []).append(c.id)

    def clone(self):
        result = super().clone()
        result._forecasts = dict(self._forecasts)
        result._endpoint_statuses = dict(self._endpoint_statuses)
        result._trip_statuses = dict(self._trip_statuses)
        result._service_statuses = dict(self._service_statuses)
        result._forecast_views = dict(self._forecast_views)
        result._status_views = dict(self._status_views)
        result._service_views = dict(self._service_views)
        return result

    def _observed(self, cid, kind):
        trip, _ = self.belief._positions[cid, kind]
        return any(record[:3] == (cid, kind, 'observed') for record in self._records.get(trip, ()))

    def _drop_forecast(self, cid, kind):
        key = cid, kind
        if key not in self._forecasts:
            return False
        del self._forecasts[key]
        trip = self.belief._positions[key][0]
        self._laws.pop(trip, None)
        self._forecast_views.pop(trip, None)
        return True

    def observe(self, cid, kind, clock):
        result = super().observe(cid, kind, clock)
        cleared = self._drop_forecast(cid, kind)
        result.update(forecast_cleared=cleared)
        result['changed'] |= cleared
        return result

    def apply_frame(self, frame, clock):
        """Consume one already available frame; no actual endpoint is an input."""
        receipt = float(frame['receipt_seconds'])
        if receipt > clock:
            raise ValueError('A forecast cannot be received before its availability clock')
        changed, cleared, statuses = [], [], []
        for trip, status in frame.get('trip_statuses', ()):
            if trip not in self._trip_cids:
                continue
            previous = self._trip_statuses.get(trip)
            if previous is not None and previous[1] > receipt:
                continue
            self._trip_statuses[trip] = status, receipt
            statuses.append(('trip', trip, status))
            if status in ('CANCELED', 'DELETED'):
                for cid in self._trip_cids[trip]:
                    for kind in ('departure', 'arrival'):
                        if self._drop_forecast(cid, kind):
                            cleared.append((cid, kind))
        for source, kind, status, predicted in frame.get('endpoint_updates', ()):
            if source not in self.source_to_local:
                continue
            cid = self.source_to_local[source]
            key = cid, kind
            previous = self._endpoint_statuses.get(key)
            trip, _ = self.belief._positions[key]
            if previous is not None and previous[1] > receipt:
                continue
            self._endpoint_statuses[key] = status, receipt
            self._status_views.pop(trip, None)
            if status in ('FORECAST', 'SCHEDULED', 'SKIPPED'):
                self._service_statuses[key] = status, receipt
                self._service_views.pop(trip, None)
            statuses.append(('endpoint', cid, kind, status))
            if status == 'FORECAST' and predicted is not None:
                if self._observed(cid, kind):
                    continue  # An operating first-hand receipt takes precedence.
                trip_status = self._trip_statuses.get(trip)
                if (trip_status is not None and trip_status[0] in ('CANCELED', 'DELETED')
                        and trip_status[1] >= receipt):
                    continue
                value = float(predicted), max(1., float(self.forecast_sd[cid])), receipt
                if self._forecasts.get(key) != value:
                    self._forecasts[key] = value
                    self._laws.pop(trip, None)
                    self._forecast_views.pop(trip, None)
                    changed.append(key)
            elif status in ('NO_DATA', 'SKIPPED') or (status == 'FORECAST' and predicted is None):
                if self._drop_forecast(cid, kind):
                    cleared.append(key)
        return dict(receipt_seconds=receipt, changed_events=changed,
                    cleared_events=cleared, statuses=statuses)

    def advance(self, clock):
        """Reveal receipts through the current execution clock only.

        Call this at real public decision times. Planning/sampling hypothetical
        future arrivals must keep this history frozen rather than advancing it.
        """
        if clock < self.message_clock:
            raise ValueError('A received message history cannot move backward in time')
        receipts = []
        while self.frame_index < len(self.frames) and self.frames[self.frame_index]['receipt_seconds'] <= clock:
            receipts.append(self.apply_frame(self.frames[self.frame_index], clock))
            self.frame_index += 1
        self.message_clock = float(clock)
        return dict(clock=float(clock), frames_consumed=len(receipts), receipts=receipts)

    def trip_status(self, trip):
        return self._trip_statuses.get(trip)

    def endpoint_status(self, cid, kind):
        return self._endpoint_statuses.get((cid, kind))

    def announced_unavailable(self, cid, kind):
        """Current public planning mask, with local operating facts first."""
        if self._observed(cid, kind):
            return False
        trip = self.belief._positions[cid, kind][0]
        notice = self._trip_statuses.get(trip)
        endpoint = self._service_statuses.get((cid, kind))
        if endpoint is not None and endpoint[0] == 'SKIPPED':
            return True
        if notice is not None and notice[0] in ('CANCELED', 'DELETED'):
            return not (endpoint is not None and endpoint[0] in ('FORECAST', 'SCHEDULED')
                        and endpoint[1] > notice[1])
        return False

    def forecast_records(self, trip):
        if trip not in self._forecast_views:
            self._forecast_views[trip] = tuple((cid, kind, *value)
                for (cid, kind), value in sorted(self._forecasts.items())
                if self.belief._positions[cid, kind][0] == trip)
        return self._forecast_views[trip]

    def _status_records(self, trip):
        if trip not in self._status_views:
            self._status_views[trip] = tuple((cid, kind, *value)
                for (cid, kind), value in sorted(self._endpoint_statuses.items())
                if self.belief._positions[cid, kind][0] == trip)
        return self._status_views[trip]

    def _service_records(self, trip):
        if trip not in self._service_views:
            self._service_views[trip] = tuple((cid, kind, *value)
                for (cid, kind), value in sorted(self._service_statuses.items())
                if self.belief._positions[cid, kind][0] == trip)
        return self._service_views[trip]

    def forecast_log_emission(self, cid, kind, predicted, sd, times):
        return -.5*((times-predicted)/sd)**2

    def law(self, trip):
        if trip not in self._laws:
            base = self.belief._law(trip, self.parameters)
            emissions = list(base.emissions)
            for cid, kind, predicted, sd, _ in self.forecast_records(trip):
                if self._observed(cid, kind):
                    continue
                _, slot = self.belief._positions[cid, kind]
                emissions[slot] = emissions[slot]+self.forecast_log_emission(
                    cid, kind, predicted, sd, base.times[slot])
            law = _ChainLaw(base.times, base.initial, base._transition, emissions,
                            base.canceled, base.stochastic)
            for cid, kind, mode, value in self._records.get(trip, ()):
                _, slot = self.belief._positions[cid, kind]
                try:
                    if mode == 'observed':
                        law, _ = departure_evidence(law, slot, -np.inf, value, observed=value)
                    else:
                        for entry, clock in value:
                            law, _ = departure_evidence(law, slot, entry, clock)
                except UnsupportedHistory as error:
                    raise UnsupportedHistory(f'{error}; trip={trip}, cid={cid}, kind={kind}, '
                                             f'evidence={mode}:{value}') from error
            self._laws[trip] = law
        return self._laws[trip]

    def signature(self, relevant_trips=None):
        if relevant_trips is None:
            trips = set(self._records) | set(self._trip_statuses)
            trips.update(self.belief._positions[key][0] for key in self._endpoint_statuses)
        else:
            trips = set(relevant_trips)
        return tuple((trip, self._records.get(trip, ()), self.forecast_records(trip),
            self._trip_statuses.get(trip), self._status_records(trip), self._service_records(trip))
            for trip in sorted(trips))

    def public_state(self):
        result = super().public_state()
        result.extend(dict(trip=self.belief._positions[cid, kind][0], cid=cid, kind=kind,
            evidence='forecast', predicted_time=prediction, sd_seconds=sd, receipt_seconds=receipt)
            for (cid, kind), (prediction, sd, receipt) in sorted(self._forecasts.items()))
        result.extend(dict(trip=trip, evidence='trip_status', status=status, receipt_seconds=receipt)
            for trip, (status, receipt) in sorted(self._trip_statuses.items()))
        result.extend(dict(trip=self.belief._positions[cid, kind][0], cid=cid, kind=kind,
            evidence='endpoint_status', status=status, receipt_seconds=receipt)
            for (cid, kind), (status, receipt) in sorted(self._endpoint_statuses.items()))
        result.extend(dict(trip=self.belief._positions[cid, kind][0], cid=cid, kind=kind,
            evidence='endpoint_service_notice', status=status, receipt_seconds=receipt)
            for (cid, kind), (status, receipt) in sorted(self._service_statuses.items()))
        return result


class ForecastPlanner(Planner):
    """Common notice masks and forecast-aware conditional transition reuse."""
    def departure_distribution(self, cid, history):
        clocks, mass, canceled = super().departure_distribution(cid, history)
        if history.announced_unavailable(cid, 'departure'):
            return clocks, np.zeros_like(mass), 1.
        return clocks, mass, canceled

    def exit_cost(self, ride, cid, history, clocks, method):
        if history.announced_unavailable(cid, 'arrival'):
            return np.full_like(clocks, self.deadline, dtype=float)
        return super().exit_cost(ride, cid, history, clocks, method)

    def _transition_key(self, trip, left, history):
        key, prior_future = super()._transition_key(trip, left, history)
        if prior_future and any(self.model._positions[cid, kind][1] > left
                                for cid, kind, *_ in history.forecast_records(trip)):
            return self._trip_key(trip, history), False
        return key, prior_future
